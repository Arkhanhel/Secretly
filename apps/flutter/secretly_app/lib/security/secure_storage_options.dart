/// Единые настройки Android для ВСЕХ мест, где создаётся защищённое хранилище.
///
/// SEC-03 (26.08.2026). Значения по умолчанию у плагина —
/// `AES_CBC_PKCS7Padding` и `RSA_ECB_PKCS1Padding`. Первое и есть находка:
/// **AES-CBC не проверяет целостность**, то есть подмену шифротекста
/// хранилище не заметит. GCM проверяет. Второе меняет PKCS#1 v1.5 на OAEP.
///
/// 🔴 ПОЧЕМУ ОДНА КОНСТАНТА, А НЕ ЧЕТЫРЕ КОПИИ.
///
/// Плагин держит все значения в ОДНОМ файле настроек (`FlutterSecureStorage`),
/// и метка использованного алгоритма там тоже одна на всех. Разойдись
/// настройки хотя бы в одном из четырёх мест — экземпляры начнут
/// перешифровывать хранилище туда-обратно при каждом запуске: один видит
/// «сохранено GCM, просят CBC», другой наоборот. Данные при этом выживают, но
/// окно отказа удваивается на ровном месте. Общая константа делает такое
/// расхождение невозможным.
///
/// 🔴 `encryptedSharedPreferences` НАМЕРЕННО ОСТАВЛЕН ВЫКЛЮЧЕННЫМ.
///
/// Его включение идёт другим путём — `checkAndMigrateToEncrypted`, — который
/// переносит ключи ПО ОДНОМУ и **удаляет каждый из старого хранилища сразу
/// после переноса**, а исключение всего цикла только пишет в журнал. Упало на
/// середине — часть ключей уже стёрта, и откат плагина к старому хранилищу
/// возвращает нас туда, где их больше нет.
///
/// Здесь лежит `secretly/db_passphrase_v1`. Его потеря означает, что база
/// SQLCipher не откроется, то есть **вся переписка человека исчезнет**. Такой
/// размен ради второго слоя той же защиты не оправдан.
///
/// Смена алгоритмов, в отличие от этого, идёт безопасным путём
/// (`reEncryptPreferences`): расшифровать всё в память, зашифровать заново,
/// записать ОДНИМ действием вместе с меткой. Ничего не удаляется, а при любом
/// исключении не записывается вовсе — данные остаются читаемыми по-старому.
/// 🔴 ОТКАТ 26.08.2026 — ПРАВКА СЛОМАЛА ЖИВОЕ УСТРОЙСТВО.
///
/// Здесь стояли `AES_GCM_NoPadding` и
/// `RSA_ECB_OAEPwithSHA_256andMGF1Padding`. После обновления поверх
/// существующей установки приложение перестало читать сохранённые значения:
/// `device_id` сменился с `7089ba66…` на `be828741…`, то есть личность
/// устройства была выпущена заново, база ушла в карантин, чаты и контакты
/// пропали с экрана.
///
/// ЧТО Я ПРОВЕРИЛ НЕДОСТАТОЧНО. Для смены ШИФРА ХРАНЕНИЯ путь плагина
/// (`reEncryptPreferences`) действительно безопасен — я прочитал его в
/// исходнике. Для смены ШИФРА КЛЮЧА я написал «тот же механизм, тот же
/// безопасный путь», **не открыв обе реализации RSA**. Ключ в AndroidKeyStore
/// создаётся с ограничением по набиванию, и существующий ключ, выпущенный под
/// PKCS#1, не годится для OAEP.
///
