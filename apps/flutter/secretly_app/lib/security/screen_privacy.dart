import 'dart:io';

import 'package:flutter/services.dart';

/// Скрытие содержимого приложения от посторонних глаз на самом устройстве.
///
/// SEC-11 (26.08.2026). Обещаний про снимки экрана интерфейс до сих пор не
/// давал, то есть расхождения не было, — но пробел был: переписка попадала и в
/// список запущенных приложений, и в запись экрана.
///
/// 🔴 ДВЕ СИСТЕМЫ ЗАЩИЩАЮТ РАЗНОЕ, И ЧЕСТНЫЙ ТЕКСТ ОБЯЗАН ЭТО РАЗЛИЧАТЬ.
///
/// * **Android** — `FLAG_SECURE` на окне: снимок экрана не сделать, запись
///   экрана даёт чёрный кадр, в списке приложений пусто.
/// * **iOS** — запретить снимок экрана НЕЛЬЗЯ, такого механизма у системы нет.
///   Закрывается только карточка в переключателе приложений: поверх окна
///   кладётся заслонка, пока приложение не активно.
///
/// Обещать на iOS защиту от скриншотов значило бы соврать, а неверное обещание
/// в мессенджере опаснее отсутствующей функции: человек станет вести себя
/// смелее, чем позволяет действительность.
///
/// 🔴 ПОЧЕМУ ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ (как в Signal). `FLAG_SECURE` ломает не
/// только злоумышленника: перестают работать демонстрация экрана и часть
/// средств доступности. Включать это за человека — значит однажды молча лишить
/// его звонка с демонстрацией или экранного диктора.
class ScreenPrivacy {
  const ScreenPrivacy._();

  static const MethodChannel _channel = MethodChannel(
    'secretly/screen_privacy',
  );

  /// Поддерживается ли защита на этой системе вообще.
  static bool get isSupported => Platform.isAndroid || Platform.isIOS;

  /// Закрывает ли защита снимки экрана и запись, а не только переключатель.
  ///
  /// На iOS — нет и не может: система не даёт такой возможности приложениям.
  static bool get blocksScreenshots => Platform.isAndroid;

  /// Применяет настройку. Возвращает `true`, если система её приняла.
  ///
  /// Отказ никогда не превращается в исключение: настройка приватности не
  /// имеет права уронить запуск. Но и молча считаться включённой она не будет —
  /// вызывающая сторона получает `false` и может это показать.
  /// 🔴 Проверки `isSupported` здесь НАМЕРЕННО НЕТ. Ранний выход по названию
  /// системы выглядел бы аккуратнее, но делал бы метод непроверяемым: на
  /// машине разработчика тест никогда не дошёл бы до канала и зеленел бы на
  /// любом коде. Отсутствие нативной части и так обрабатывается ниже — тем же
  /// способом и с тем же результатом.
  static Future<bool> apply({required bool enabled}) async {
    try {
      final ok = await _channel.invokeMethod<bool>('setEnabled', <String, Object?>{
        'enabled': enabled,
      });
      return ok ?? false;
    } on MissingPluginException {
      // Сборка без нативной части (тесты, инструменты) — не повод падать.
      return false;
    } on PlatformException {
      return false;
    }
  }
}
