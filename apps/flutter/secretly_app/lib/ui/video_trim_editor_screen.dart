/// Filmstrip + dual trim handles. Reports the selected [startMs] / [endMs].
class VideoTrimTrack extends StatelessWidget {
  const VideoTrimTrack({
    super.key,
    required this.durationMs,
    required this.startMs,
    required this.endMs,
    required this.minTrimMs,
    required this.frames,
    required this.positionMs,
    required this.onChanged,
  });

  final int durationMs;
  final int startMs;
  final int endMs;
  final int minTrimMs;
  final List<File> frames;
  final int positionMs;
  final void Function(int startMs, int endMs) onChanged;

  static const double _handleW = 14;
  static const double _trackH = 56;

  @override
  Widget build(BuildContext context) {
    final accent = Theme.of(context).colorScheme.primary;
    return LayoutBuilder(
      builder: (context, constraints) {
        final fullW = constraints.maxWidth;
        final usableW = (fullW - _handleW * 2).clamp(1.0, double.infinity);
        double msToX(int ms) =>
            _handleW + (durationMs == 0 ? 0 : ms / durationMs) * usableW;
        int xToMs(double x) =>
            (((x - _handleW) / usableW) * durationMs).round().clamp(0, durationMs);

        final startX = msToX(startMs);
        final endX = msToX(endMs);
        final playX = msToX(positionMs.clamp(startMs, endMs));

        return SizedBox(
          height: _trackH,
          width: fullW,
          child: Stack(
            children: <Widget>[
              // Filmstrip.
              Positioned(
                left: _handleW,
                right: _handleW,
                top: 0,
                bottom: 0,
                child: ClipRRect(
                  borderRadius: BorderRadius.circular(8),
                  child: frames.isEmpty
                      ? Container(color: Colors.white10)
                      : Row(
                          children: <Widget>[
                            for (final f in frames)
                              Expanded(
                                child: Image.file(
                                  f,
                                  fit: BoxFit.cover,
                                  height: _trackH,
                                  gaplessPlayback: true,
                                  errorBuilder: (_, _, _) => const BrokenMediaBox(iconSize: 12, onDarkSurface: true),
                                ),
                              ),
                          ],
                        ),
                ),
              ),
              // Dim the trimmed-away regions.
              Positioned(
                left: _handleW,
                width: (startX - _handleW).clamp(0.0, usableW),
                top: 0,
                bottom: 0,
                child: const ColoredBox(color: Color(0x99000000)),
              ),
              Positioned(
                left: endX,
                right: _handleW,
                top: 0,
                bottom: 0,
                child: const ColoredBox(color: Color(0x99000000)),
              ),
              // Selection border.
              Positioned(
                left: startX,
                width: (endX - startX).clamp(0.0, fullW),
                top: 0,
                bottom: 0,
                child: DecoratedBox(
                  decoration: BoxDecoration(
                    border: Border.symmetric(
                      horizontal: BorderSide(color: accent, width: 2.5),
                    ),
                  ),
                ),
              ),
              // Playhead.
              Positioned(
                left: playX - 1,
                top: 2,
                bottom: 2,
                child: Container(width: 2, color: Colors.white),
              ),
              // Left handle.
              _buildHandle(
                left: startX - _handleW,
                accent: accent,
                isLeft: true,
                onDrag: (dx) {
                  final newStart = xToMs(startX + dx);
                  onChanged(
                    newStart.clamp(0, endMs - minTrimMs),
                    endMs,
                  );
                },
              ),
              // Right handle.
              _buildHandle(
                left: endX,
                accent: accent,
                isLeft: false,
                onDrag: (dx) {
                  final newEnd = xToMs(endX + dx);
                  onChanged(
                    startMs,
                    newEnd.clamp(startMs + minTrimMs, durationMs),
                  );
                },
              ),
            ],
          ),
        );
      },
    );
  }

  Widget _buildHandle({
    required double left,
    required Color accent,
    required bool isLeft,
    required void Function(double dx) onDrag,
  }) {
    return Positioned(
      left: left,
      top: 0,
      bottom: 0,
      width: _handleW,
      child: GestureDetector(
        behavior: HitTestBehavior.opaque,
        onHorizontalDragUpdate: (d) => onDrag(d.delta.dx),
        child: Container(
          decoration: BoxDecoration(
            color: accent,
            borderRadius: BorderRadius.horizontal(
              left: isLeft ? const Radius.circular(8) : Radius.zero,
              right: isLeft ? Radius.zero : const Radius.circular(8),
            ),
          ),
          child: const Center(
            child: Icon(Icons.drag_indicator, color: Colors.white, size: 14),
          ),
        ),
      ),
    );
  }
}

/// Resizable crop rectangle drawn over the video. [crop] is fractional (0..1)
/// of the displayed video area.
class _CropOverlay extends StatelessWidget {
  const _CropOverlay({required this.crop, required this.onChanged});

  final Rect crop;
  final ValueChanged<Rect> onChanged;

  static const double _min = 0.12;

  @override
  Widget build(BuildContext context) {
    final accent = Theme.of(context).colorScheme.primary;
    return LayoutBuilder(
      builder: (context, constraints) {
        final w = constraints.maxWidth;
        final h = constraints.maxHeight;
        final rect = Rect.fromLTRB(
          crop.left * w,
          crop.top * h,
          crop.right * w,
          crop.bottom * h,
        );

        Rect clampFrac(Rect r) {
          var l = r.left.clamp(0.0, 1.0 - _min);
          var t = r.top.clamp(0.0, 1.0 - _min);
          var rr = r.right.clamp(l + _min, 1.0);
          var bb = r.bottom.clamp(t + _min, 1.0);
          return Rect.fromLTRB(l, t, rr, bb);
        }

        void moveBody(Offset delta) {
          final dx = delta.dx / w;
          final dy = delta.dy / h;
          var l = crop.left + dx;
          var t = crop.top + dy;
          final cw = crop.width;
          final ch = crop.height;
          l = l.clamp(0.0, 1.0 - cw);
          t = t.clamp(0.0, 1.0 - ch);
          onChanged(Rect.fromLTWH(l, t, cw, ch));
        }

        void dragCorner(Offset delta, {required bool left, required bool top}) {
          final dx = delta.dx / w;
          final dy = delta.dy / h;
          var l = crop.left;
          var t = crop.top;
          var r = crop.right;
          var b = crop.bottom;
          if (left) {
            l += dx;
          } else {
            r += dx;
          }
          if (top) {
            t += dy;
          } else {
            b += dy;
          }
          onChanged(clampFrac(Rect.fromLTRB(l, t, r, b)));
        }

        const handle = 28.0;
        return Stack(
          children: <Widget>[
            // Dim outside the crop.
            IgnorePointer(
              child: CustomPaint(
                size: Size(w, h),
                painter: _CropDimPainter(rect: rect, accent: accent),
              ),
            ),
            // Body drag.
            Positioned.fromRect(
              rect: rect,
              child: GestureDetector(
                behavior: HitTestBehavior.translucent,
                onPanUpdate: (d) => moveBody(d.delta),
              ),
            ),
            _corner(rect.topLeft, handle,
                (d) => dragCorner(d, left: true, top: true)),
            _corner(rect.topRight, handle,
                (d) => dragCorner(d, left: false, top: true)),
            _corner(rect.bottomLeft, handle,
                (d) => dragCorner(d, left: true, top: false)),
            _corner(rect.bottomRight, handle,
                (d) => dragCorner(d, left: false, top: false)),
          ],
        );
      },
    );
  }

  Widget _corner(Offset center, double size, ValueChanged<Offset> onDrag) {
    return Positioned(
      left: center.dx - size / 2,
      top: center.dy - size / 2,
      width: size,
      height: size,
      child: GestureDetector(
        behavior: HitTestBehavior.opaque,
        onPanUpdate: (d) => onDrag(d.delta),
        child: const SizedBox.expand(),
      ),
    );
  }
}

class _CropDimPainter extends CustomPainter {
  _CropDimPainter({required this.rect, required this.accent});

  final Rect rect;
  final Color accent;

  @override
  void paint(Canvas canvas, Size size) {
    final full = Offset.zero & size;
    final dim = Paint()..color = Colors.black.withValues(alpha: 0.45);
    final outside = Path()
      ..addRect(full)
      ..addRect(rect)
      ..fillType = PathFillType.evenOdd;
    canvas.drawPath(outside, dim);

    final border = Paint()
      ..color = Colors.white
      ..style = PaintingStyle.stroke
      ..strokeWidth = 2;
    canvas.drawRect(rect, border);

    // Rule-of-thirds grid.
    final grid = Paint()
      ..color = Colors.white.withValues(alpha: 0.35)
      ..strokeWidth = 1;
    for (var i = 1; i < 3; i++) {
      final dx = rect.left + rect.width * i / 3;
      canvas.drawLine(Offset(dx, rect.top), Offset(dx, rect.bottom), grid);
      final dy = rect.top + rect.height * i / 3;
      canvas.drawLine(Offset(rect.left, dy), Offset(rect.right, dy), grid);
    }

    // Corner accents.
    final corner = Paint()
      ..color = accent
      ..style = PaintingStyle.stroke
      ..strokeWidth = 4
      ..strokeCap = StrokeCap.round;
    const len = 18.0;
    void drawCorner(Offset c, double sx, double sy) {
      canvas.drawLine(c, c.translate(sx * len, 0), corner);
      canvas.drawLine(c, c.translate(0, sy * len), corner);
    }

    drawCorner(rect.topLeft, 1, 1);
    drawCorner(rect.topRight, -1, 1);
    drawCorner(rect.bottomLeft, 1, -1);
    drawCorner(rect.bottomRight, -1, -1);
  }

  @override
  bool shouldRepaint(_CropDimPainter old) =>
      old.rect != rect || old.accent != accent;
}


/// TELEGRAM SEND EDITOR (2026-07-17): shared helpers so the gallery pre-send
/// editor reuses this screen's proven FFmpeg pipeline.
///
/// Filmstrip frames for a trim track — small JPEGs in a temp dir.
Future<List<File>> videoTrimFilmstripFrames(
  String sourcePath, {
  int count = 12,
  int heightPx = 120,
}) async {
  try {
    final dir = await getTemporaryDirectory();
    final stamp = DateTime.now().millisecondsSinceEpoch;
    final outDir = Directory(p.join(dir.path, 'vstrip_$stamp'));
    await outDir.create(recursive: true);
    // Probe-free: rely on fps sampling across the whole clip.
    final pattern = p.join(outDir.path, 'f_%03d.jpg');
    final cmd =
        "-y -i '$sourcePath' -vf \"select='not(mod(n\\,max(1\\,floor(n_frames/$count))))',scale=-2:$heightPx\" "
        "-vsync vfr -frames:v $count -q:v 5 '$pattern'";
    var session = await FFmpegKit.execute(cmd);
    var rc = await session.getReturnCode();
    if (!ReturnCode.isSuccess(rc)) {
      // Fallback: time-based sampling (n_frames unavailable in some containers).
      final cmd2 =
          "-y -i '$sourcePath' -vf \"fps=$count/10,scale=-2:$heightPx\" "
          "-vsync vfr -frames:v $count -q:v 5 '$pattern'";
      session = await FFmpegKit.execute(cmd2);
      rc = await session.getReturnCode();
      if (!ReturnCode.isSuccess(rc)) return const <File>[];
    }
    final files =
        outDir
            .listSync()
            .whereType<File>()
            .where((f) => f.path.toLowerCase().endsWith('.jpg'))
            .toList()
          ..sort((a, b) => a.path.compareTo(b.path));
    return files;
  } catch (_) {
    return const <File>[];
  }
}

/// Fast trim-only export (stream copy, re-encode fallback). Returns the new
/// file path, or null on failure.
Future<String?> exportTrimmedVideoFile(
  String sourcePath, {
  required int startMs,
  required int endMs,
}) async {
  try {
    final dir = await getTemporaryDirectory();
    final stamp = DateTime.now().millisecondsSinceEpoch;
    final outPath = p.join(dir.path, 'vsend_$stamp.mp4');
    final startSec = (startMs / 1000).toStringAsFixed(3);
    final durSec = ((endMs - startMs) / 1000)
        .clamp(0.1, 100000.0)
        .toStringAsFixed(3);
    final copyCmd =
        "-y -ss $startSec -i '$sourcePath' -t $durSec "
        "-c copy -movflags +faststart '$outPath'";
    var session = await FFmpegKit.execute(copyCmd);
    var rc = await session.getReturnCode();
    final outFile = File(outPath);
    if (ReturnCode.isSuccess(rc) &&
        outFile.existsSync() &&
        outFile.lengthSync() > 0) {
      return outPath;
    }
    final reencCmd =
        "-y -ss $startSec -i '$sourcePath' -t $durSec "
        "-c:v libx264 -preset veryfast -crf 23 -pix_fmt yuv420p "
        "-c:a aac -b:a 128k -movflags +faststart '$outPath'";
    session = await FFmpegKit.execute(reencCmd);
    rc = await session.getReturnCode();
    if (ReturnCode.isSuccess(rc) &&
        outFile.existsSync() &&
        outFile.lengthSync() > 0) {
      return outPath;
    }
    return null;
  } catch (_) {
    return null;
  }
}
