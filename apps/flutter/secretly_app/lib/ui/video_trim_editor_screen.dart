/// Result returned by [VideoTrimEditorScreen]: the (possibly re-encoded) output
/// path plus the final duration in milliseconds.
class VideoTrimEditorResult {
  const VideoTrimEditorResult({required this.path, required this.durationMs});

  final String path;
  final int durationMs;
}

/// Telegram-style post-capture video editor. Lets the user trim the clip by
/// duration (filmstrip with draggable handles) and crop the frame (resizable
/// rectangle) before sending. Exports through FFmpeg — trim-only uses a fast
/// stream copy, crop re-encodes with libx264.
class VideoTrimEditorScreen extends StatefulWidget {
  const VideoTrimEditorScreen({
    super.key,
    required this.sourcePath,
    required this.localize,
  });

  final String sourcePath;
  final String Function(String ru, String en) localize;

  @override
  State<VideoTrimEditorScreen> createState() => _VideoTrimEditorScreenState();
}

class _VideoTrimEditorScreenState extends State<VideoTrimEditorScreen> {
  VideoPlayerController? _controller;
  bool _ready = false;
  bool _exporting = false;
  String? _error;

  // Trim range, in milliseconds, relative to the source clip.
  int _durationMs = 0;
  int _startMs = 0;
  int _endMs = 0;
  static const int _minTrimMs = 1000;

  // Crop rectangle as fractions (0..1) of the displayed video area. Default is
  // the full frame (no crop).
  Rect _crop = const Rect.fromLTWH(0, 0, 1, 1);
  bool _cropMode = false;

  // Filmstrip thumbnails generated by FFmpeg.
  List<File> _frames = const <File>[];

  String _t(String ru, String en) => widget.localize(ru, en);

  bool get _hasCrop =>
      _crop.left > 0.001 ||
      _crop.top > 0.001 ||
      _crop.right < 0.999 ||
      _crop.bottom < 0.999;

  @override
  void initState() {
    super.initState();
    unawaited(_init());
  }

  @override
  void dispose() {
    _controller?.removeListener(_onTick);
    _controller?.dispose();
    super.dispose();
  }

  Future<void> _init() async {
    try {
      final controller = VideoPlayerController.file(File(widget.sourcePath));
      await controller.initialize();
      controller.addListener(_onTick);
      await controller.setLooping(false);
      final durMs = controller.value.duration.inMilliseconds;
      if (!mounted) {
        await controller.dispose();
        return;
      }
      setState(() {
        _controller = controller;
        _durationMs = durMs;
        _startMs = 0;
        _endMs = durMs;
        _ready = true;
      });
      unawaited(controller.play());
      unawaited(_generateFrames());
    } catch (_) {
      if (mounted) {
        setState(() => _error = _t('Не удалось открыть видео', 'Failed to open video'));
      }
    }
  }

  void _onTick() {
    final controller = _controller;
    if (controller == null || !controller.value.isInitialized) return;
    final pos = controller.value.position.inMilliseconds;
    // Loop strictly inside the trimmed range.
    if (pos >= _endMs - 40 || pos < _startMs - 40) {
      unawaited(controller.seekTo(Duration(milliseconds: _startMs)));
      if (controller.value.isPlaying) {
        // keep playing from start
      }
    }
    if (mounted) setState(() {});
  }

  Future<void> _generateFrames() async {
    try {
      final dir = await getTemporaryDirectory();
      final stamp = DateTime.now().millisecondsSinceEpoch;
      final outDir = Directory(p.join(dir.path, 'vtrim_$stamp'));
      await outDir.create(recursive: true);
      const count = 10;
      final durSec = (_durationMs / 1000).clamp(0.001, 100000.0);
      final interval = (durSec / count).clamp(0.04, 100000.0);
      final pattern = p.join(outDir.path, 'f_%03d.jpg');
      final cmd =
          "-y -i '${widget.sourcePath}' -vf \"fps=1/$interval,scale=-2:140\" "
          "-vsync vfr -q:v 5 '$pattern'";
      final session = await FFmpegKit.execute(cmd);
      final rc = await session.getReturnCode();
      if (!ReturnCode.isSuccess(rc)) return;
      final files = outDir
          .listSync()
          .whereType<File>()
          .where((f) => f.path.toLowerCase().endsWith('.jpg'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
      if (!mounted) return;
      setState(() => _frames = files);
    } catch (_) {
      // Filmstrip is decorative — ignore failures, handles still work.
    }
  }

  void _togglePlay() {
    final controller = _controller;
    if (controller == null) return;
    setState(() {
      if (controller.value.isPlaying) {
        controller.pause();
      } else {
        if (controller.value.position.inMilliseconds >= _endMs - 60) {
          controller.seekTo(Duration(milliseconds: _startMs));
        }
        controller.play();
      }
    });
  }

  void _onTrimChanged(int startMs, int endMs) {
    final controller = _controller;
    setState(() {
      _startMs = startMs.clamp(0, _durationMs);
      _endMs = endMs.clamp(_startMs + _minTrimMs, _durationMs);
    });
    if (controller != null) {
      final pos = controller.value.position.inMilliseconds;
      if (pos < _startMs || pos > _endMs) {
        unawaited(controller.seekTo(Duration(milliseconds: _startMs)));
      }
    }
  }

  Future<void> _export() async {
    final controller = _controller;
    if (controller == null || _exporting) return;
    final trimmed = _startMs > 60 || _endMs < _durationMs - 60;
    final cropped = _hasCrop;

    // Nothing changed → return the original untouched.
    if (!trimmed && !cropped) {
      Navigator.of(context).pop(
        VideoTrimEditorResult(path: widget.sourcePath, durationMs: _durationMs),
      );
      return;
    }

    setState(() => _exporting = true);
    await controller.pause();
    try {
      final dir = await getTemporaryDirectory();
      final stamp = DateTime.now().millisecondsSinceEpoch;
      final outPath = p.join(dir.path, 'vedit_$stamp.mp4');
      final startSec = (_startMs / 1000).toStringAsFixed(3);
      final durSec = ((_endMs - _startMs) / 1000).clamp(0.1, 100000.0)
          .toStringAsFixed(3);

      String cmd;
      if (cropped) {
        // Map the fractional crop onto the oriented frame (FFmpeg auto-rotates
        // by default, matching what video_player displays). Even dimensions are
        // required for yuv420p.
        final size = controller.value.size;
        final vw = size.width;
        final vh = size.height;
        int even(double v) {
          var i = v.round();
          if (i.isOdd) i -= 1;
          return i < 2 ? 2 : i;
        }

        final cw = even(_crop.width * vw);
        final ch = even(_crop.height * vh);
        final cx = (_crop.left * vw).round().clamp(0, (vw - cw).round());
        final cy = (_crop.top * vh).round().clamp(0, (vh - ch).round());
        cmd =
            "-y -ss $startSec -i '${widget.sourcePath}' -t $durSec "
            "-vf \"crop=$cw:$ch:$cx:$cy\" "
            "-c:v libx264 -preset veryfast -crf 23 -pix_fmt yuv420p "
            "-c:a aac -b:a 128k -movflags +faststart '$outPath'";
      } else {
        // Trim only → fast, lossless stream copy preserving rotation metadata.
        cmd =
            "-y -ss $startSec -i '${widget.sourcePath}' -t $durSec "
            "-c copy -movflags +faststart '$outPath'";
      }

      final session = await FFmpegKit.execute(cmd);
      final rc = await session.getReturnCode();
      final outFile = File(outPath);
      if (ReturnCode.isSuccess(rc) && outFile.existsSync() &&
          outFile.lengthSync() > 0) {
        if (!mounted) return;
        Navigator.of(context).pop(
          VideoTrimEditorResult(
            path: outPath,
            durationMs: _endMs - _startMs,
          ),
        );
        return;
      }
      // Fallback: if a trim-only stream copy failed (e.g. odd container), retry
      // by re-encoding before giving up.
      if (!cropped) {
        final reenc =
            "-y -ss $startSec -i '${widget.sourcePath}' -t $durSec "
            "-c:v libx264 -preset veryfast -crf 23 -pix_fmt yuv420p "
            "-c:a aac -b:a 128k -movflags +faststart '$outPath'";
        final s2 = await FFmpegKit.execute(reenc);
        final rc2 = await s2.getReturnCode();
        if (ReturnCode.isSuccess(rc2) && outFile.existsSync() &&
            outFile.lengthSync() > 0) {
          if (!mounted) return;
          Navigator.of(context).pop(
            VideoTrimEditorResult(
              path: outPath,
              durationMs: _endMs - _startMs,
            ),
          );
          return;
        }
      }
      throw Exception('export failed');
    } catch (_) {
      if (!mounted) return;
      setState(() {
        _exporting = false;
        _error = _t('Не удалось обработать видео', 'Failed to process video');
      });
    }
  }

  String _formatDuration(int ms) {
    final total = (ms / 1000).round();
    final m = total ~/ 60;
    final s = total % 60;
    return '$m:${s.toString().padLeft(2, '0')}';
  }

  @override
  Widget build(BuildContext context) {
    final controller = _controller;
    final media = MediaQuery.of(context);
    return Scaffold(
      backgroundColor: Colors.black,
      body: Stack(
        children: <Widget>[
          if (!_ready || controller == null)
            Center(
              child: _error != null
                  ? Text(_error!, style: const TextStyle(color: Colors.white70))
                  : const CircularProgressIndicator(color: Colors.white),
            )
          else
            Column(
              children: <Widget>[
                SizedBox(height: media.padding.top + 4),
                _buildTopBar(controller),
                Expanded(
                  child: Center(
                    child: AspectRatio(
                      aspectRatio: controller.value.aspectRatio == 0
                          ? 1
                          : controller.value.aspectRatio,
                      child: Stack(
                        fit: StackFit.expand,
                        children: <Widget>[
                          GestureDetector(
                            onTap: _cropMode ? null : _togglePlay,
                            child: VideoPlayer(controller),
                          ),
                          if (_cropMode)
                            _CropOverlay(
                              crop: _crop,
                              onChanged: (r) => setState(() => _crop = r),
                            ),
                          if (!_cropMode && !controller.value.isPlaying)
                            const Center(
                              child: _PlayBadge(),
                            ),
                        ],
                      ),
                    ),
                  ),
                ),
                _buildTrimBar(),
                SizedBox(height: media.padding.bottom + 10),
              ],
            ),
          if (_exporting)
            Positioned.fill(
              child: ColoredBox(
                color: Colors.black.withValues(alpha: 0.6),
                child: Center(
                  child: Column(
                    mainAxisSize: MainAxisSize.min,
                    children: <Widget>[
                      const CircularProgressIndicator(color: Colors.white),
                      const SizedBox(height: 16),
                      Text(
                        _t('Обработка видео…', 'Processing video…'),
                        style: const TextStyle(color: Colors.white),
                      ),
                    ],
                  ),
                ),
              ),
            ),
        ],
      ),
    );
  }

  Widget _buildTopBar(VideoPlayerController controller) {
    final selMs = _endMs - _startMs;
    return Padding(
      padding: const EdgeInsets.symmetric(horizontal: 8),
      child: Row(
        children: <Widget>[
          IconButton(
            onPressed: _exporting ? null : () => Navigator.of(context).pop(),
            icon: const Icon(Icons.close, color: Colors.white),
          ),
          const Spacer(),
          Text(
            _formatDuration(selMs),
            style: const TextStyle(
              color: Colors.white,
              fontWeight: FontWeight.w700,
              fontSize: 15,
            ),
          ),
          const Spacer(),
          IconButton(
            tooltip: _t('Кадрировать', 'Crop'),
            onPressed: _exporting
                ? null
                : () => setState(() => _cropMode = !_cropMode),
            icon: Icon(
              Icons.crop,
              color: _cropMode ? Theme.of(context).colorScheme.primary
                  : Colors.white,
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildTrimBar() {
    return Padding(
      padding: const EdgeInsets.fromLTRB(16, 8, 16, 4),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: <Widget>[
          VideoTrimTrack(
            durationMs: _durationMs,
            startMs: _startMs,
            endMs: _endMs,
            minTrimMs: _minTrimMs,
            frames: _frames,
            positionMs: _controller?.value.position.inMilliseconds ?? 0,
            onChanged: _onTrimChanged,
          ),
          const SizedBox(height: 16),
          Row(
            children: <Widget>[
              IconButton(
                onPressed: _togglePlay,
                icon: Icon(
                  (_controller?.value.isPlaying ?? false)
                      ? Icons.pause
                      : Icons.play_arrow,
                  color: Colors.white,
                  size: 30,
                ),
              ),
              const Spacer(),
              _SendButton(
                onTap: _exporting ? null : _export,
                label: _t('Отправить', 'Send'),
              ),
            ],
          ),
        ],
      ),
    );
  }
}

