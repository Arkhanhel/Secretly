/// Демонстрационные комнаты: существуют ТОЛЬКО в местной базе.
///
/// 🔴 ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ.
///
/// Такая комната видна в списке и в неё можно писать, но на сервере её нет:
/// любой запрос к релею по ней возвращает `404 room not found`. Кнопки,
/// которым нужен сервер — созвон, ссылка-приглашение, — в ней не сработают
/// никогда, и показывать их значит обещать то, чего не будет.
///
/// Проверка живёт в одном месте, потому что мест, где она нужна, уже два:
/// окно созвона (`calls/room_call_window.dart`) и подробности комнаты
/// (`chat/details/room_details_view.dart`). Разъехавшись, они дали бы
/// комнату, где созвон честно объяснён, а приглашение падает ошибкой.
///
/// Слова владельца про такую комнату: «эта группа видимо тестовая, в мобильной
/// версии у меня её вообще нет, поэтому она не звонит».
library;

/// True, если идентификатор принадлежит демонстрационной комнате.
bool isDemoRoomId(String? id) {
  final trimmed = (id ?? '').trim();
  if (trimmed.isEmpty) return false;
  return trimmed.startsWith('group:demo:') || trimmed.startsWith('demo:');
}
