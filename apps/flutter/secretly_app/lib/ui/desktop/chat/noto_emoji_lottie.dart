/// True when [text], stripped of whitespace, is a single emoji that we know
/// how to render via Noto Lottie. The mobile «solo emoji» bubble uses the
/// same gate (`_isSoloNotoEmoji`).
bool isSoloNotoEmoji(String text) {
  final t = text.trim();
  return t.isNotEmpty && kDesktopNotoCodepoints.containsKey(t);
}

/// True if [emoji] has an animated Lottie file we can fetch.
bool isAnimatableNotoEmoji(String emoji) =>
    kDesktopNotoCodepoints.containsKey(emoji.trim());

final Map<String, File> _notoFileCache = <String, File>{};
final Map<String, Future<File?>> _notoLoadFutures = <String, Future<File?>>{};

/// Loads the Lottie JSON file for [emoji] from disk or the Noto CDN. The
/// returned file is cached in memory for the life of the process and on
/// disk in the system temp directory under `noto_emoji_{cp}.json`.
Future<File?> loadNotoLottieFile(String emoji) {
  final codepoint = kDesktopNotoCodepoints[emoji.trim()];
  if (codepoint == null) return Future<File?>.value(null);
  return _notoLoadFutures[codepoint] ??= _doLoadNotoLottie(codepoint);
}

Future<File?> _doLoadNotoLottie(String codepoint) async {
  if (_notoFileCache.containsKey(codepoint)) return _notoFileCache[codepoint];
  try {
    final dir = await getTemporaryDirectory();
    final file = File(p.join(dir.path, 'noto_emoji_$codepoint.json'));
    if (await file.exists()) {
      // Desktop shares the mobile cache filename, but not necessarily the
      // mobile cache: heal a file downloaded before the `tm` + `sr` fix.
      try {
        final healed = normalizeNotoLottieBytes(await file.readAsBytes());
        if (healed != null) await file.writeAsBytes(healed);
      } catch (_) {}
      _notoFileCache[codepoint] = file;
      return file;
    }
    final uri = Uri.parse(
      'https://fonts.gstatic.com/s/e/notoemoji/latest/$codepoint/lottie.json',
    );
    final response =
        await http_pkg.get(uri).timeout(const Duration(seconds: 15));
    if (response.statusCode == 200) {
      final normalized = normalizeNotoLottieBytes(response.bodyBytes);
      await file.writeAsBytes(normalized ?? response.bodyBytes);
      _notoFileCache[codepoint] = file;
      return file;
    }
  } catch (_) {
    // Fall through to null — the caller renders the bare unicode emoji.
  }
  return null;
}

/// How a [NotoEmojiLottie] should play. Mirrors mobile's `_NotoLottieMode`.
enum NotoLottieMode {
  /// First frame only, no ticking. Used in the emoji picker grid.
  preview,

  /// Plays once on mount or on widget-key change, then snaps to frame 0.
  once,

  /// Loops forever. Used by the quick-react bar so the icons feel alive.
  looping,
}

/// Animated Noto emoji rendered via Lottie. Falls back to the bare unicode
/// emoji while the JSON downloads (or forever if the network is offline).
class NotoEmojiLottie extends StatefulWidget {
  const NotoEmojiLottie({
    super.key,
    required this.emoji,
    this.size = 44.0,
    this.mode = NotoLottieMode.looping,
  });

  final String emoji;
  final double size;
  final NotoLottieMode mode;

  @override
  State<NotoEmojiLottie> createState() => _NotoEmojiLottieState();
}

/// Счётчик для неповторяющихся ключей сторожа видимости.
int _notoVisibilitySeq = 0;

class _NotoEmojiLottieState extends State<NotoEmojiLottie>
    with SingleTickerProviderStateMixin {
  File? _file;
  AnimationController? _ctrl;
  int _loadGeneration = 0;

  /// 🔴 БЕСКОНЕЧНОЕ ПРОИГРЫВАНИЕ КРУТИТСЯ, ТОЛЬКО ПОКА ЭМОДЗИ ВИДНО.
  ///
  /// Зацикленная анимация заказывает кадр каждый вsync. Без этого сторожа один
  /// смайлик в тексте держал бы ВСЁ окно в непрерывной перерисовке, а в ленте
  /// на тысячу сообщений таких смайликов сотни — включая уехавшие далеко за
  /// край экрана. Телефон этот урок уже прошёл и сторожит тем же способом.
  ///
  /// Задержка `VisibilityDetector` в 500 мс означает, что при прокрутке это не
  /// дёргается на каждый кадр.
  late final Key _visibilityKey = Key(
    'noto-emoji-vis-${_notoVisibilitySeq++}',
  );
  bool _visible = true;

  void _onVisibilityChanged(VisibilityInfo info) {
    final visible = info.visibleFraction > 0;
    if (visible == _visible) return;
    _visible = visible;
    final ctrl = _ctrl;
    if (ctrl == null || widget.mode != NotoLottieMode.looping) return;
    if (visible) {
      if (!ctrl.isAnimating) ctrl.repeat();
    } else {
      ctrl.stop();
    }
  }

  void _loadEmojiFile(String emoji) {
    final currentGeneration = ++_loadGeneration;
    final codepoint = kDesktopNotoCodepoints[emoji.trim()];
    if (codepoint != null && _notoFileCache.containsKey(codepoint)) {
      _file = _notoFileCache[codepoint];
      return;
    }

    _file = null;
    loadNotoLottieFile(emoji).then((f) {
      if (!mounted || currentGeneration != _loadGeneration) return;
      if (widget.emoji != emoji) return;
      setState(() => _file = f);
    });
  }

  @override
  void initState() {
    super.initState();
    if (widget.mode == NotoLottieMode.looping) {
      // Своим контроллером, а не `repeat: true` у `Lottie.file`: остановить
      // чужой внутренний контроллер, когда эмодзи уехало за край, нечем.
      _ctrl = AnimationController(
        vsync: this,
        duration: const Duration(seconds: 2),
      );
    } else if (widget.mode == NotoLottieMode.once) {
      _ctrl = AnimationController(
        vsync: this,
        duration: const Duration(seconds: 2),
      )..addStatusListener((status) {
          // Some Noto Lottie JSONs end with a transparent frame, so snap
          // back to frame 0 after completion so the emoji stays visible.
          if (status == AnimationStatus.completed && mounted) {
            _ctrl!.value = 0.0;
          }
        });
    }
    _loadEmojiFile(widget.emoji);
  }

  @override
  void didUpdateWidget(covariant NotoEmojiLottie oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (oldWidget.emoji != widget.emoji) {
      setState(() => _file = null);
      _ctrl?.reset();
      _loadEmojiFile(widget.emoji);
      return;
    }
    if (oldWidget.mode != widget.mode && widget.mode == NotoLottieMode.once) {
      _ctrl?.reset();
    }
  }

  @override
  void dispose() {
    _ctrl?.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final f = _file;
    if (f == null) return _fallback();
    switch (widget.mode) {
      case NotoLottieMode.preview:
        return SizedBox(
          width: widget.size,
          height: widget.size,
          child: Lottie.file(
            f,
            width: widget.size,
            height: widget.size,
            animate: false,
            fit: BoxFit.contain,
            errorBuilder: (_, __, ___) => _fallback(),
          ),
        );
      case NotoLottieMode.once:
        final ctrl = _ctrl!;
        return SizedBox(
          width: widget.size,
          height: widget.size,
          child: Lottie.file(
            f,
            width: widget.size,
            height: widget.size,
            controller: ctrl,
            onLoaded: (comp) {
              ctrl.duration = comp.duration;
              if (ctrl.status == AnimationStatus.dismissed) ctrl.forward();
            },
            fit: BoxFit.contain,
            errorBuilder: (_, __, ___) => _fallback(),
          ),
        );
      case NotoLottieMode.looping:
        return VisibilityDetector(
          key: _visibilityKey,
          onVisibilityChanged: _onVisibilityChanged,
          child: SizedBox(
            width: widget.size,
            height: widget.size,
            child: Lottie.file(
              f,
              width: widget.size,
              height: widget.size,
              controller: _ctrl,
              // Часть Noto-анимаций заканчивается прозрачным кадром: крутим
              // почти полный круг, чтобы смайлик не мигал пустотой.
              onLoaded: (comp) {
                final ctrl = _ctrl;
                if (ctrl == null) return;
                ctrl.duration = comp.duration;
                if (_visible && !ctrl.isAnimating) {
                  ctrl.repeat(min: 0.01, max: 0.97, period: comp.duration * 0.96);
                }
              },
              fit: BoxFit.contain,
              errorBuilder: (_, __, ___) => _fallback(),
            ),
          ),
        );
    }
  }

  Widget _fallback() => SizedBox(
        width: widget.size,
        height: widget.size,
        child: Center(
          child: Text(
            widget.emoji,
            style: TextStyle(fontSize: widget.size * 0.72),
            textAlign: TextAlign.center,
          ),
        ),
      );
}
