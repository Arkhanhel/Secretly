// Desktop port of the mobile Noto-emoji-animation helper that lives in
// `lib/ui/chat_screen.dart` (PR3.7 + PR3.8 + PR3.9, 2026-05-19,
// SPRINT2_AUDIT §13 / §14).
//
// Mobile renders animated reactions and bubble-free «solo emoji» messages
// using Lottie JSON pulled from the Google Noto CDN
// (https://fonts.gstatic.com/s/e/notoemoji/latest/{codepoint}/lottie.json).
// The codepoint map and the loader are private (`_notoCodepoints`,
// `_loadNotoLottieFile`) inside `chat_screen.dart`, so the desktop side
// duplicates the table here rather than touching the mobile screen — the
// user has been explicit that the mobile design must not be modified in
// this sprint.
//
// PR3.8 (2026-05-19): the codepoint table has been expanded from ~90
// entries (mobile parity) to the FULL Noto Emoji Animation catalog from
// https://googlefonts.github.io/noto-emoji-animation/data/api.json (881
// entries — every animatable emoji including all skin-tone variants and
// ZWJ sequences). The mobile design will catch up over a separate PR; for
// now desktop simply has a strictly-larger known set, which is fine because
// the runtime gate is "key present in this map → render Lottie", with a
// safe text fallback otherwise.
//
// PR3.9 (2026-05-19): added category metadata so the expanded reactions
// picker can render Telegram-style category sections with a left-rail jump
// strip. The category slug for each emoji is read from the upstream
// manifest's `categories[0]` field, slugified to `lower_snake_case`. The
// nine slugs that appear in the current manifest are:
//
//   smileys_and_emotions, people, animals_and_nature, food_and_drink,
//   travel_and_places, activities_and_events, objects, symbols, flags
//
// `kDesktopNotoCategoryOrder` preserves first-appearance order from the
// manifest, and `kDesktopNotoCategoryLabelsRu` gives human-readable
// Russian display names for the picker section headers.
//
// Disk caching reuses the same `noto_emoji_{codepoint}.json` filename in
// the system temp dir, so once mobile downloads an emoji the desktop picks
// it up for free (and vice versa).

