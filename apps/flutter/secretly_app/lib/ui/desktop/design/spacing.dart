/// Отступы окна.
///
/// · ДВЕ ШКАЛЫ, И ЭТО НЕ НЕБРЕЖНОСТЬ.
///
/// [DSpace] начинался как «сетка 4»: 4, 8, 12, 16, 20, 24, 32, 48. Легенда
/// макета (строка 66) тоже объявляет сетку 4 — и сама разметка макета ей НЕ
/// СЛЕДУЕТ. Пересчитано по файлу макета:
///
///   зазоры:   10 (40 раз) · 6 (39) · 8 (34) · 5 (30) · 9 (29) · 7 (22)
///   отступы:  10 (54) · 8 (46) · 9 (40) · 12 (26) · 11 (25) · 5 (24) · 14 (22)
///
/// То есть у макета нет шага 4 — у него есть каждое целое от 5 до 14. Пока
/// нечётные ступени были невыразимы, каждая девятка в коде превращалась в
/// восьмёрку или двенадцать, и строки расходились с макетом на точку-две в
/// местах, где точка видна: высота строки списка, поля пузыря, фишка реакции.
///
/// Поэтому ступени макета заведены как есть — числом в имени, чтобы их не
/// приняли за новую смысловую шкалу. Имена «размерами одежды» (xs…xl4) не
/// тронуты: за ними 450 обращений, и переписывать их ради единообразия значит
/// переписать всё окно ради ничего.
///
/// Правило простое:
///   • нужен ОДИН отступ и макет даёт число — берём [p5]…[p14];
///   • нужен ритм, числа в макете нет — берём xs…xl4;
///   • четвёрка чисел прямо из макета (поля пузыря, `fromLTRB(13, 10, 13, 8)`)
///     пишется числами: четыре ссылки на токены в одной строке читаются хуже
///     самих чисел, а число там и есть смысл.
class DSpace {
  DSpace._();

  // Сетка 4 — ритм там, где макет числа не даёт.
  static const double xs = 4;
  static const double s = 8;
  static const double m = 12;
  static const double l = 16;
  static const double xl = 20;
  static const double xl2 = 24;
  static const double xl3 = 32;
  static const double xl4 = 48;

  // Ступени самого макета. Число в имени — это и есть значение.
  static const double p5 = 5;
  static const double p6 = 6;
  static const double p7 = 7;
  static const double p9 = 9;
  static const double p10 = 10;
  static const double p11 = 11;
  static const double p13 = 13;
  static const double p14 = 14;
}
