/// Скругления десктопа.
///
/// 🔴 СТУПЕНИ СВЕРЕНЫ С ИСХОДНИКОМ МАКЕТА (14.09.2026), а не взяты на глаз.
///
/// Сколько раз какое скругление встречается в макете:
/// 9 — 56, 10 — 47, 11 — 37, 12 — 32, 8 — 20, 15 — 20, 13 — 15, 16 — 10,
/// 7 — 7, 14 — 7, 6 — 5. **Восемнадцати в макете нет ни одного раза**, а
/// именно им был обрезан пузырь сообщения — самая заметная форма в окне.
///
/// Менять `sm`/`md`/`lg` списком было нельзя: на них висит семьдесят с лишним
/// мест, и слепая подмена дала бы «поехало всё сразу». Поэтому добавлены
/// НАЗВАННЫЕ ПО ЧИСЛУ ступени, а переезжают на них только те места, у которых
/// в макете есть свой размер.
class DRadii {
  DRadii._();

  static const double sm = 6;
  static const double md = 10;
  static const double lg = 14;
  static const double pill = 999;

  /// 20 вхождений: кнопки строки действий над сообщением, чипы «PRO».
  static const double r8 = 8;

  /// Главный радиус контролов макета (56 вхождений): мелкие кнопки, чипы.
  static const double r9 = 9;

  /// 37 вхождений: кнопки дока, поля.
  static const double r11 = 11;

  /// 32 вхождения: строка списка, кнопки созвона 40×40.
  static const double r12 = 12;

  /// 20 вхождений: плитка рейки, всплывающие карточки, сцена созвона.
  static const double r15 = 15;

  /// Максимум макета (10 вхождений): рамка окна и ПУЗЫРЬ СООБЩЕНИЯ.
  ///
  /// Пузырь был обрезан восемнадцатью — размером, которого в макете нет
  /// вовсе. Сторона со срезом при этом стояла верно и осталась как была.
  static const double r16 = 16;
}
