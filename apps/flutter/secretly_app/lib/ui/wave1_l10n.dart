import 'package:flutter/widgets.dart';

String wave1LocaleTagFromContext(BuildContext context) {
  final locale = Localizations.localeOf(context);
  return wave1LocaleTag(locale.languageCode, countryCode: locale.countryCode);
}

String wave1LocaleTag(String languageCode, {String? countryCode}) {
  final language = languageCode.trim().toLowerCase();
  final country = (countryCode ?? '').trim().toUpperCase();
  if (language == 'pt' && country == 'BR') return 'pt_BR';
  if (language == 'pt') return 'pt';
  if (<String>{'de', 'en', 'es', 'fr', 'ru', 'uk'}.contains(language)) {
    return language;
  }
  return 'en';
}

bool wave1LocaleIsRussian(BuildContext context) {
  return wave1LocaleTagFromContext(context) == 'ru';
}

String wave1Text(
  BuildContext context, {
  required String ru,
  required String en,
  String? uk,
  String? es,
  String? pt,
  String? ptBr,
  String? fr,
  String? de,
}) {
  return wave1TextForLocale(
    wave1LocaleTagFromContext(context),
    ru: ru,
    en: en,
    uk: uk,
    es: es,
    pt: pt,
    ptBr: ptBr,
    fr: fr,
    de: de,
  );
}

String wave1TextForLocale(
  String localeTag, {
  required String ru,
  required String en,
  String? uk,
  String? es,
  String? pt,
  String? ptBr,
  String? fr,
  String? de,
}) {
  final direct = switch (localeTag) {
    'ru' => ru,
    'uk' => uk,
    'es' => es,
    'pt' => pt,
    'pt_BR' => ptBr ?? pt,
    'fr' => fr,
    'de' => de,
    _ => en,
  };
  if (direct != null) return direct;
  final mapped = _wave1TextTranslations[en];
  if (mapped == null) return en;
  return mapped[localeTag] ??
      (localeTag == 'pt_BR' ? mapped['pt'] : null) ??
      en;
}

