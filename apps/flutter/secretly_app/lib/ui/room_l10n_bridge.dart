String roomLocaleTagFromContext(BuildContext context) {
  final locale = Localizations.localeOf(context);
  return roomLocaleTag(locale.languageCode, countryCode: locale.countryCode);
}

String roomLocaleTag(String languageCode, {String? countryCode}) {
  final language = languageCode.trim().toLowerCase();
  final country = (countryCode ?? '').trim().toUpperCase();
  if (language == 'pt' && country == 'BR') return 'pt_BR';
  if (language == 'pt') return 'pt';
  if (<String>{'de', 'en', 'es', 'fr', 'ru', 'uk'}.contains(language)) {
    return language;
  }
  return 'en';
}

String roomLocaleTagFromString(String? rawLocaleTag) {
  final raw = (rawLocaleTag ?? '').trim();
  if (raw.isEmpty) return 'en';
  final normalized = raw.replaceAll('-', '_');
  final parts = normalized.split('_');
  return roomLocaleTag(
    parts.first,
    countryCode: parts.length > 1 ? parts[1] : null,
  );
}

String roomTextForLocale(
  String localeTag, {
  required String ru,
  required String en,
  String? uk,
  String? es,
  String? pt,
  String? ptBr,
  String? fr,
  String? de,
}) {
  final direct = switch (localeTag) {
    'ru' => ru,
    'uk' => uk,
    'es' => es,
    'pt' => pt,
    'pt_BR' => ptBr ?? pt,
    'fr' => fr,
    'de' => de,
    _ => en,
  };
  if (direct != null) return direct;
  return _roomTextTranslations[en]?[localeTag] ?? en;
}

String roomText(
  BuildContext context, {
  required String ru,
  required String en,
  String? uk,
  String? es,
  String? pt,
  String? ptBr,
  String? fr,
  String? de,
}) {
  return roomTextForLocale(
    roomLocaleTagFromContext(context),
    ru: ru,
    en: en,
    uk: uk,
    es: es,
    pt: pt,
    ptBr: ptBr,
    fr: fr,
    de: de,
  );
}

bool roomLocaleIsRussian(BuildContext context) {
  return roomLocaleTagFromContext(context) == 'ru';
}

