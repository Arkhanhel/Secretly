/// Облегчённая сборка Android: что в ней есть и чего нет.
///
/// Полная сборка весит около 140 МБ, и для телефона с 16 ГБ памяти или
/// мобильным интернетом по карточке это препятствие. Примерно 45 МБ из них —
/// три набора библиотек, без которых мессенджер остаётся мессенджером:
/// перевод сообщений (ML Kit), расшифровка голосовых (whisper) и обработка
/// видео (FFmpeg).
///
/// Переключатель один на обе стороны сборки: Gradle по свойству
/// `secretly.lite` выбрасывает библиотеки из пакета, а этот флаг
/// (`--dart-define=SECRETLY_LITE=true`) убирает из приложения то, что без
/// них не работает. Выставляются вместе — `tools/macos_build_android_release.sh
/// --lite`.
///
/// 🔴 ЧЕГО ЭТОТ ФЛАГ НЕ КАСАЕТСЯ. Безопасность в облегчённой сборке ровно та
/// же: сквозное шифрование, исчезающие сообщения, защита от снимков экрана,
/// PIN, набор восстановления, сверка контактов, пути против блокировок. Чтение
/// QR-кода тоже остаётся — без него не привязать устройство. Экономия идёт
/// только за счёт удобств.
library;

/// Сборка без библиотек перевода, расшифровки голосовых и обработки видео.
const bool kLiteBuild = bool.fromEnvironment('SECRETLY_LITE');

/// Доступна ли обработка видео (FFmpeg): сжатие при отправке, миниатюры,
/// обрезка, видеокружки, кадр из анимированного портрета.
const bool kVideoToolsAvailable = !kLiteBuild;

/// Доступен ли перевод сообщений на устройстве (ML Kit).
const bool kTranslationAvailable = !kLiteBuild;

/// Доступна ли расшифровка голосовых сообщений на устройстве (whisper).
const bool kVoiceTranscriptionAvailable = !kLiteBuild;
