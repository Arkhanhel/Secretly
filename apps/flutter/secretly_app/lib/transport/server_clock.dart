/// Поправка к часам устройства, вычисленная по ответам сервера.
///
/// ЗАЧЕМ. Запросы к серверу ключей подписываются вместе с временной меткой, и
/// сервер отвергает метку, разошедшуюся с его часами больше чем на пять минут —
/// это защита от повторного воспроизведения запроса, и она правильная.
///
/// Но следствие бьёт по человеку, чьи часы сбились: подписанные запросы
/// перестают приниматься, список устройств собеседника получить нельзя, а без
/// него **сообщение просто некуда отправить**. Поле 26.08.2026: шесть устройств
/// дали около четырёх тысяч таких отказов за трое суток, у одного — двадцать
/// восемь в час непрерывно. Их владельцы видели, что сообщения не уходят, и не
/// могли понять почему: предупреждение о часах показывалось только при
/// регистрации устройства.
///
/// РЕШЕНИЕ. Каждый ответ HTTP несёт стандартный заголовок `Date` — время
/// сервера. Разница между ним и часами устройства и есть поправка; подписывая
/// запрос, прибавляем её к своей метке. Часы устройства при этом не трогаются:
/// поправка живёт только внутри приложения.
///
/// 🔴 ГРАНИЦЫ, БЕЗ КОТОРЫХ ЛЕКАРСТВО ХУЖЕ БОЛЕЗНИ:
///
/// * поправка меньше [_minMeaningfulSkewMs] игнорируется — это сетевой шум, а
///   не расхождение часов;
/// * поправка больше [_maxTrustedSkewMs] отбрасывается: такая разница означает
///   не сбитые часы, а что-то, чего мы не понимаем, и слепо доверять ей нельзя;
/// * точность заголовка — секунды, поэтому поправка никогда не бывает точнее
///   секунды. Для окна в пять минут этого достаточно с большим запасом.
class ServerClock {
  ServerClock._();

  static final ServerClock instance = ServerClock._();

  /// Ниже этого расхождение считается шумом и не применяется.
  static const _minMeaningfulSkewMs = 10 * 1000;

  /// Выше этого поправке не доверяем вовсе.
  ///
  /// Было сутки. Поле 17.09.2026: самый шумный отказ на реле (788 за 40 минут)
  /// давало устройство, у которого дата сдвинута на день вперёд, а часы — ещё
  /// на 3,6 минуты: 24 ч 03,6 мин, чуть за прежней границей. Такому человеку
  /// поправка не помогала вовсе. Неделя покрывает «не тот день» с запасом;
  /// поправка берётся только из ответов наших серверов по TLS, а большие
  /// сдвиги TLS не пропустит сам (сертификат ещё или уже недействителен).
  static const _maxTrustedSkewMs = 7 * 24 * 60 * 60 * 1000;

  int _offsetMs = 0;
  int _lastUpdatedAtMs = 0;

  /// Текущая поправка в миллисекундах: сколько прибавить к часам устройства,
  /// чтобы получить время сервера. Ноль — поправка не нужна или неизвестна.
  int get offsetMs => _offsetMs;

  /// Есть ли осмысленная поправка (то есть часы устройства заметно сбиты).
  bool get hasSkew => _offsetMs != 0;

  /// Время, которым следует подписывать запросы к серверу.
  int nowMs() => DateTime.now().millisecondsSinceEpoch + _offsetMs;

  /// Учесть время из заголовка `Date` очередного ответа.
  ///
  /// Возвращает `true`, если поправка изменилась — вызывающая сторона может
  /// это отметить в диагностике.
  bool observeServerDate(DateTime serverTimeUtc) {
    final localMs = DateTime.now().millisecondsSinceEpoch;
    final serverMs = serverTimeUtc.toUtc().millisecondsSinceEpoch;
    final skew = serverMs - localMs;

    if (skew.abs() > _maxTrustedSkewMs) {
      // Больше недели разницы — это не сбитые часы, а неизвестная нам ситуация.
      // Оставляем как есть: неверная поправка сделает недействительными и те
      // запросы, которые сейчас проходят.
      return false;
    }

    final next = skew.abs() < _minMeaningfulSkewMs ? 0 : skew;
    _lastUpdatedAtMs = localMs;
    if (next == _offsetMs) return false;
    _offsetMs = next;
    return true;
  }

  /// Строка для отчёта диагностики.
  String describe() {
    if (_lastUpdatedAtMs == 0) return 'часы: сверка с сервером не выполнялась';
    if (_offsetMs == 0) return 'часы: расхождения с сервером нет';
    final seconds = (_offsetMs / 1000).round();
    final sign = seconds > 0 ? '+' : '';
    return 'часы: расхождение с сервером $sign$seconds с — поправка применяется';
  }

  /// Только для тестов.
  void resetForTest() {
    _offsetMs = 0;
    _lastUpdatedAtMs = 0;
  }
}
