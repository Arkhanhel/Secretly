/// Режим доступа к своему набору стикеров.
///
/// Ш-1 из `docs/TZ_STICKER_SHARING_2026-08-08.md`: **дать имя тому, что уже
/// есть**, ничего не меняя в поведении.
///
/// 🔴 ПОЧЕМУ ЭТО ВООБЩЕ НУЖНО. Разбор перед работой показал, что запрос стоял
/// иначе, чем выглядел: «доступ только тем, кому отправляю» **уже работает** —
/// свои наборы ездят зашифрованными блобами, сервер хранит только шифртекст, а
/// ключ едет внутри E2EE-сообщения. То есть строить надо было не этот режим, а
/// возможность его НАЗВАТЬ и отличить от других.
library;

enum StickerShareMode {
  /// Набор только у меня. Никуда не уезжает, кроме моих же копий.
  personal('personal'),

  /// Кому отправил — у того и есть. **Нынешнее поведение** и значение по
  /// умолчанию для всех существующих наборов.
  sentOnly('sent_only'),

  /// Доступен всем через каталог.
  ///
  /// 🔴 НЕ РЕАЛИЗОВАН, и это не забывчивость. Публикация означает, что **сервер
  /// видит картинки открытыми**, то есть осознанный отказ от главного свойства
  /// продукта для этого набора. Плюс на сервере нет ни приёма загрузки, ни
  /// лимитов, ни модерации — а без модерации первый же неприемлемый набор
  /// становится юридической проблемой владельца сервера.
  ///
  /// Значение объявлено заранее, чтобы старые сборки не спотыкались о него,
  /// если новая когда-нибудь его запишет (см. [fromStorage] — неизвестное
  /// значение читается как [sentOnly], а не роняет чтение набора).
  published('published');

  const StickerShareMode(this.storageValue);

  /// То, что лежит в `sticker_packs.share_mode`.
  final String storageValue;

  /// Значение по умолчанию.
  ///
  /// 🔴 Именно `sentOnly`, а не `personal`: любое другое значение молча поменяло
  /// бы поведение существующих наборов при обновлении, а Ш-1 обязан не менять
  /// ничего.
  static const StickerShareMode fallback = StickerShareMode.sentOnly;

  /// Разбор из базы.
  ///
  /// 🔴 Неизвестное значение — это [fallback], а НЕ исключение. Столбец могла
  /// записать более новая сборка (или откат вернул старый код к новым данным), и
  /// падение здесь означало бы набор, который перестал открываться, — потерю
  /// вместо непонимания.
  static StickerShareMode fromStorage(Object? raw) {
    if (raw is! String) return fallback;
    final value = raw.trim().toLowerCase();
    for (final mode in StickerShareMode.values) {
      if (mode.storageValue == value) return mode;
    }
    return fallback;
  }

  /// Реализован ли режим на сегодня.
  ///
  /// 🔴 Отдельный признак, а не «просто не показывать в интерфейсе». Значение
  /// может приехать из базы, из копии или из будущей сборки, и код обязан уметь
  /// сказать «этого я не умею» вместо того, чтобы делать вид, что умеет.
  bool get isSupported => this != StickerShareMode.published;

  /// Уезжает ли набор с устройства при отправке стикера.
  ///
  /// Для [personal] — нет: это и есть весь смысл режима.
  bool get allowsSendingToPeers => this != StickerShareMode.personal;

  /// Видит ли сервер картинки открытыми.
  ///
  /// 🔴 Единственное место, где этот вопрос имеет ответ «да», — публикация.
  /// Держать его отдельным свойством нужно затем, чтобы интерфейс мог
  /// предупредить человека ДО решения, а не после.
  bool get exposesContentToServer => this == StickerShareMode.published;
}
