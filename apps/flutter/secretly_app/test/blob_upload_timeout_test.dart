import 'package:flutter_test/flutter_test.dart';
import 'package:secretly_app/transport/blob_client.dart';

/// ТАЙМАУТ ЗАЛИВКИ БЛОБА (найдено 02.09.2026, аудит передачи файлов).
///
/// Здесь стояли жёсткие 90 секунд, и ни один вызывающий их не переопределял.
/// Порог буферного пути для видео — 24 МБ, а сжатое видео (1920p, CRF 25)
/// обычно как раз 5–25 МБ, то есть почти всегда попадало именно сюда. По
/// собственной оценке проекта «медленный мобильный» — 250 КБ/с; 24 МБ на такой
/// скорости идут около 98 секунд.
///
/// То есть отправка сорвалась бы АРИФМЕТИЧЕСКИ, без единого сбоя сети. Докачки
/// нет: повтор начинается с нуля и упирается в те же 90 секунд — «видео не
/// уходит никогда», причём воспроизводимо.
void main() {
  group('таймаут заливки блоба', () {
    test('мелкое вложение сохраняет прежние 90 секунд, а не теряет их', () {
      expect(
        BlobClient.uploadTimeoutFor(64 * 1024),
        const Duration(seconds: 90),
        reason: 'до правки любой файл имел 90 секунд. Пол в 30 секунд, взятый '
            'по образцу копии переписки, УКОРОТИЛ бы голосовые и снимки '
            'втрое — правка против срывов вводила бы новые',
      );
    });

    test('🔴 НИ ОДИН размер не получает меньше, чем до правки', () {
      // Главное свойство: изменение одностороннее. Раньше таймаут был ровно
      // 90 секунд для всего; после правки он обязан быть не меньше для любого
      // размера, иначе где-то отправка станет срываться раньше прежнего.
      const previousBehaviour = Duration(seconds: 90);
      const sizes = <int>[
        0,
        50 * 1024, // голосовое
        512 * 1024, // сжатый снимок
        3 * 1024 * 1024, // снимок высокого качества
        5 * 1024 * 1024, // короткое видео
        10 * 1024 * 1024,
        15 * 1024 * 1024, // до правки здесь было 72 с — регрессия
        20 * 1024 * 1024,
        24 * 1024 * 1024, // порог буферного пути
        200 * 1024 * 1024,
      ];
      for (final size in sizes) {
        expect(
          BlobClient.uploadTimeoutFor(size),
          greaterThanOrEqualTo(previousBehaviour),
          reason: 'размер $size байт получил бы меньше прежних 90 секунд',
        );
      }
    });

    test('видео в 24 МБ получает больше прежних 90 секунд', () {
      final timeout = BlobClient.uploadTimeoutFor(24 * 1024 * 1024);
      expect(
        timeout.inSeconds,
        greaterThan(90),
        reason: 'ровно тот случай, что срывался: при 250 КБ/с такому файлу '
            'нужно около 98 секунд, а отводилось 90',
      );
      // 24 МиБ / 256000 Б/с = 98,3 с → округление вверх 99 с, плюс 10 с запаса.
      expect(timeout.inSeconds, 109);
    });

    test('огромное вложение упирается в потолок 10 минут', () {
      expect(
        BlobClient.uploadTimeoutFor(500 * 1024 * 1024),
        const Duration(minutes: 10),
        reason: 'зависшая сеть не должна держать отправку вечно',
      );
    });

    test('таймаут растёт вместе с размером', () {
      final small = BlobClient.uploadTimeoutFor(5 * 1024 * 1024);
      final large = BlobClient.uploadTimeoutFor(20 * 1024 * 1024);
      expect(
        large,
        greaterThan(small),
        reason: 'смысл правки в том, что предел считается ОТ РАЗМЕРА, '
            'а не стоит на месте, пока файлы растут',
      );
    });

    test('нулевой размер не даёт нулевого или отрицательного предела', () {
      expect(
        BlobClient.uploadTimeoutFor(0),
        const Duration(seconds: 90),
        reason: 'вырожденный вход обязан вести в пол, а не в мгновенный срыв',
      );
    });

    test('скорость расчёта та же, что принята для копии переписки', () {
      // Обе величины считаются от 250 КБ/с с запасом в 10 секунд. Расхождение
      // означало бы, что один и тот же «медленный мобильный» оценивается в
      // проекте двумя разными способами. Пол при этом РАЗНЫЙ и намеренно:
      // здесь прежним поведением были 90 секунд, у копии — 8.
      const bytes = 40 * 1024 * 1024; // выше пола, чтобы виден был сам расчёт
      expect(
        BlobClient.uploadTimeoutFor(bytes).inSeconds,
        (bytes / (250 * 1024)).ceil() + 10,
      );
    });
  });
}
