// У анимированного кольца аватара должен быть СВОЙ слой.
//
// 🔴 Почему это сторожится по исходнику. Кольцо перерисовывается на каждом тике
// общего атласа украшений. Без собственного слоя эта перерисовка пачкает слой
// родителя — то есть всю переписку: в нативном профиле было видно, как
// растровый поток заново рисует текст ВСЕХ пузырей из-за одного значка в шапке.
//
// Замер 12.09.2026, один процесс, одна сессия, отладочная сборка:
//
//     без чата                            1,9 %
//     чат с анимированным украшением      43,7 %  → 35,5 % после границы
//     чат без украшений                    5,9 %
//
// Поведением это не поймать: виджет-тест прогоняет кадры сам и на лишнюю
// растеризацию не жалуется. Поэтому — текстом.

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

void main() {
  final avatar = File(
    'lib/ui/desktop/primitives/avatar.dart',
  ).readAsStringSync();

  test('🔴 анимированное кольцо обёрнуто в RepaintBoundary', () {
    final code = avatar
        .split('\n')
        .where((l) => !l.trimLeft().startsWith('//'))
        .join('\n');

    // Граница обязана стоять между масштабированием и содержимым кольца.
    final i = code.indexOf('FittedBox');
    expect(i, greaterThan(0), reason: 'кольцо больше не масштабируется — '
        'проверку надо переписать под новую разметку, а не удалять');

    final tail = code.substring(i, (i + 400).clamp(0, code.length));
    expect(
      tail.contains('RepaintBoundary'),
      isTrue,
      reason: 'без своего слоя перерисовка кольца снова будет тянуть за собой '
          'весь чат: замер давал 43,7% против 5,9% в чате без украшений',
    );
    expect(
      tail.indexOf('RepaintBoundary') < tail.indexOf('frame.builder'),
      isTrue,
      reason: 'граница обязана быть ВЫШЕ содержимого кольца, иначе она ничего '
          'не изолирует',
    );
  });

  test('канонический размер кольца остался один', () {
    // Граница стоит ВНУТРИ FittedBox нарочно: масштабирование готового слоя —
    // дешёвая композиция, а пересчёт содержимого под каждый размер вернул бы
    // ту самую историю с четырьмя независимыми контурами (36, 40, 88, 96).
    expect(
      avatar.contains('kDesktopFrameCanonicalPx'),
      isTrue,
      reason: 'если размер перестал быть каноническим, вернутся несколько '
          'независимых контуров сразу',
    );
  });
}
