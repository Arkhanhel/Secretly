      //   * экран подключения к телефону (`onboarding/`) — первое, что видит
      //     новый человек, и до сих пор единственное окно, которое
      //     разговаривало с ним только по-русски;
      //   * меню правой кнопки на сообщении — подписи передаются в него
      //     снаружи, потому что оно собирается статическим методом и своего
      //     контекста не имеет;
      //   * левый список переписок, включая разделы по дням.
      //
      // Про список отдельно: его заголовки («ЗАКРЕПЛЁННЫЕ», «СЕГОДНЯ») были
      // ОДНОВРЕМЕННО подписью и признаком раздела — по ним сравнивали, куда
      // ставить булавку и где склеивать одинаковые подряд. Перевести их, не
      // разведя эти две роли, было нельзя: перевод сломал бы разбиение.
      // Теперь в списке лежит метка (`pinned`, `today`), а подпись берётся из
      // переводов при отрисовке.
      //
      // Числительные («N участников», «N стикеров») вынесены правилом
      // множественного числа, а не склейкой строк: по-русски это три формы
      // плюс исключение на 11-14.
      //
      // Целыми файлами — сознательно: половина файла на переводах, половина
      // литералами читается хуже, чем любая из крайностей, и следующий, кто
      // сюда придёт, не поймёт, где проходит граница.
      //
      // 1127 -> 1081 (19.09.2026, вторая партия): окно созвона целиком.
      // Это второй по величине экран после настроек и единственный, где текст
      // появляется в ОТВЕТ НА СБОЙ: «сервер не выдал медиа-канал», «нет связи
      // с сервером», «не удалось войти». Человек читает их в худшую минуту, и
      // читать их на чужом языке — отдельная беда поверх основной.
      paths: ['lib/ui/desktop'],
      baseline: 1081,
      slack: 60,
    ),
    _Scope(
      name: 'desktop entrypoint + platform layer',
      paths: ['lib/main_desktop.dart', 'lib/desktop'],
      baseline: 3,
      slack: 2,
    ),
  ];

  for (final scope in scopes) {
    test('hardcoded Russian strings do not increase — ${scope.name}', () {
      final files = _dartFilesIn(scope.paths);
      expect(
        files,
        isNotEmpty,
        reason:
            'no Dart files under ${scope.paths.join(', ')} — run this test '
            'from apps/flutter/secretly_app, and check the paths still exist',
      );

      final (:total, :perFile) = _countCyrillicLiterals(files);

      if (total > scope.baseline) {
        final worst = perFile.entries.toList()
          ..sort((a, b) => b.value.compareTo(a.value));
        fail(
          'Hardcoded Russian strings grew in ${scope.name}: '
          '$total unique, baseline ${scope.baseline}.\n'
          'New user-facing text on desktop should go through `l10n`, not a\n'
          'literal. Heaviest files:\n'
          '${worst.take(5).map((e) => '  ${e.key}: ${e.value}').join('\n')}',
        );
      }

      expect(
        total,
        greaterThan(scope.baseline - scope.slack - 1),
        reason:
            'Strings were extracted from ${scope.name} ($total now, baseline '
            '${scope.baseline}) — lower the baseline in this test to lock the '
            'win in.',
      );
    });
  }
}

class _Scope {
  const _Scope({
    required this.name,
    required this.paths,
    required this.baseline,
    required this.slack,
  });

  final String name;

  /// Files or directories, relative to `apps/flutter/secretly_app`.
  final List<String> paths;
  final int baseline;
  final int slack;
}

List<File> _dartFilesIn(List<String> paths) {
  final files = <File>[];
  for (final path in paths) {
    final file = File(path);
    if (file.existsSync()) {
      if (path.endsWith('.dart')) files.add(file);
      continue;
    }
    final dir = Directory(path);
    if (!dir.existsSync()) continue;
    for (final entity in dir.listSync(recursive: true)) {
      if (entity is File && entity.path.endsWith('.dart')) files.add(entity);
    }
  }
  return files;
}

/// Counts distinct quoted literals containing at least one Cyrillic letter.
///
/// Both quote styles are matched. Doc and line comments are skipped so Russian
/// PROSE explaining the code is never counted as UI text — this codebase
/// comments heavily in Russian and those are not translation debt.
({int total, Map<String, int> perFile}) _countCyrillicLiterals(
  List<File> files,
) {
  final literals = <RegExp>[
    RegExp(r"'[^'\n]*[А-Яа-яЁё][^'\n]*'"),
    RegExp(r'"[^"\n]*[А-Яа-яЁё][^"\n]*"'),
  ];
  final comment = RegExp(r'^\s*(///|//)');

  final found = <String>{};
  final perFile = <String, int>{};

  for (final file in files) {
    var fileCount = 0;
    for (final line in file.readAsLinesSync()) {
      if (comment.hasMatch(line)) continue;
      for (final literal in literals) {
        for (final match in literal.allMatches(line)) {
          found.add(match.group(0)!);
          fileCount++;
        }
      }
    }
    if (fileCount > 0) perFile[file.path] = fileCount;
  }

  return (total: found.length, perFile: perFile);
}
