/// Stops the desktop's hardcoded-string debt from growing.
///
/// The desktop tree carries ~900 Russian literals against a handful of `l10n`
/// lookups, so the interface-language picker is gated off (`kDesktopUiLocalized`)
/// rather than shipped as a placebo. Extracting them is a large translation
/// job — nine hundred strings across eight locales — and it cannot be done
/// safely in one pass.
///
/// What CAN be done today is stop it getting worse. This is a ratchet: it
/// records the current count and fails when new hardcoded strings appear, so
/// the debt only ever shrinks. When you extract a batch, lower the scope's
/// `baseline` in the same commit — that is the whole maintenance burden.
///
/// It deliberately does not demand that any particular file be clean, because
/// a rule nobody can satisfy today gets disabled tomorrow.
///
/// **Coverage widened 08.09.2026** (`DESKTOP_STRATEGY_REVIEW_2026-09-08.md` §5,
/// item 4). Two holes were closed without moving any baseline:
///
///  * The entrypoint and platform layer were unscanned, and the tray menu
///    ("Показать окно" / "Скрыть окно" / "Выйти") is user-facing text that was
///    never counted. Now its own scope, baseline 3.
///  * Only single-quoted literals were matched, so `"..."` was a free pass.
///    Both quote styles are matched now; the count is unchanged because the
///    tree currently holds zero double-quoted Cyrillic literals.
///
/// **Deliberately out of scope:** `lib/ui/desktop_chats_workspace.dart`
/// (Surface B). It is legacy, scheduled for removal once the tablet path moves
/// to Surface A (`DESKTOP_COMPLETION_TZ.md` §9), and it is reached from the
/// *mobile* entrypoint — ratcheting it would protect code we intend to delete.
