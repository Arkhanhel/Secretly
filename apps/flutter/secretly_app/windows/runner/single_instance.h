#ifndef RUNNER_SINGLE_INSTANCE_H_
#define RUNNER_SINGLE_INSTANCE_H_

#include <windows.h>

// 🔴 ОДИН SECRETLY НА ПОЛЬЗОВАТЕЛЯ, И ПОВТОРНЫЙ ЗАПУСК ВЫВОДИТ ОКНО
// (28.09.2026).
//
// Крестик прячет окно в трей. Раньше повторный запуск Secretly.exe на Windows
// просто выходил: единственный путь назад был значок в трее, а он из-за PNG
// вместо ICO был пустым. Приложение оставалось живым и недоступным.
//
// Теперь новый процесс ещё ДО запуска Flutter спрашивает именованный мьютекс.
// Занят — ищет главное окно уже запущенного Secretly по нашей метке, отдаёт
// ему право выйти на передний план (оно есть у процесса, который человек
// только что запустил) и шлёт сигнал «покажись». Сам сразу выходит: второй
// движок Flutter даже не стартует.

// Метка на главном окне: по ней новый процесс отличает наше окно от окон
// других приложений на Flutter — класс окна у всех одинаковый.
extern const wchar_t kSecretlyMainWindowProp[];

// Номер сообщения «покажись» (RegisterWindowMessage — общий для процессов).
UINT SecretlyShowWindowMessage();

// Держит мьютекс до конца процесса. Возвращает true, если Secretly уже
// запущен и ему передана просьба показаться — тогда вызывающему надо выйти.
bool HandOffToRunningInstance();

#endif  // RUNNER_SINGLE_INSTANCE_H_
